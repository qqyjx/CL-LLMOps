"""Train CAEVN per dataset from LLM-generated verification triples.

Implements the paper Section 5 protocol: hypotheses are generated by
running the LLM on the TRAIN split with M=1; evidence items are
retrieved from the knowledge base; labels are assigned by comparing
the LLM's stated diagnosis against the ground-truth fault label:

  support    -- diagnosis correct and cited evidence consistent
  contradict -- cited evidence conflicts with the actual signal
                features / retrieved data (rule-judge flagged)
  neutral    -- otherwise (e.g. wrong diagnosis, consistent evidence)

The balanced pool targets --n-triples (hypothesis, evidence, label)
triples (default 9,000; each generated episode contributes its
retrieved-evidence triple plus a ground-truth-supporting and a
confuser-contradicting evidence set, i.e. 3 triples per episode).
For the margin-ranking objective in framework/verification/caevn.py
each episode is packed as one (h, E_support, E_contradict) pair.

Architecture and schedule follow the paper: frozen all-MiniLM-L6-v2
encoder (384-d), 4-head cross-attention (d_k=96), 2-layer MLP (256),
50 epochs AdamW lr 1e-3. The MLP ablation verifier (mlp_verifier
variant) is trained on the same pairs unless --skip-mlp.

Checkpoints: experiments/checkpoints/caevn_{dataset}.pt (and
caevn_{dataset}_mlp.pt, caevn_{dataset}_beta{b}.pt with --beta);
label-distribution stats go to caevn_{dataset}_train_stats.json.

Local testing (no GPU/vLLM):
    ASOC_LLM_MODE=mock python experiments/train_caevn.py \
        --datasets pq16 cwru --mock-llm --n-triples 300 --epochs 3
"""

import argparse
import json
import time
from pathlib import Path

import numpy as np
import torch

from config import (
    MODEL_DIR, RANDOM_SEED, CAEVN_EPOCHS, CAEVN_ENTROPY_BETA,
    EVIDENCE_TOP_K,
)
from data import load_splits
from evaluation.metrics import RuleBasedJudge, diagnosis_to_class_id
from evaluation.action_rules import get_class_names
from framework.hypothesis import HypothesisGenerator
from framework.knowledge_base import build_knowledge_base
from framework.llm_client import MockLLMClient, get_default_client
from framework.pipeline import build_alarm_classifier, get_sentence_encoder
from framework.verification.caevn import CAEVNTrainer, MLPVerifier


def _topk_class_evidence(kb, h_emb, class_name, k=EVIDENCE_TOP_K):
    """Top-k KB embeddings tagged with `class_name`, ranked by
    similarity to the hypothesis embedding (padded by repetition)."""
    idx = [i for i, d in enumerate(kb.docs) if d["tag"] == class_name]
    if not idx:  # should not happen: every class has channel-1/3 docs
        idx = list(range(len(kb.docs)))
    embs = kb.embeddings[idx]
    h = h_emb / (np.linalg.norm(h_emb) + 1e-8)
    order = np.argsort(embs @ h)[::-1][:k]
    chosen = embs[order]
    while len(chosen) < k:
        chosen = np.vstack([chosen, chosen[:k - len(chosen)]])
    return chosen.astype(np.float32)


def generate_triples(dataset_name, n_triples, llm, seed, verbose=True,
                     workers=1):
    """Generate labeled verification triples on the train split (M=1).

    Episodes are independent (read-only alarm/KB/encoder), so with
    workers>1 they run in a thread pool.  Determinism is preserved by
    construction: episode i always uses a fresh client seeded ``seed + i``
    (vLLM: the single request of episode i then draws exactly the stream
    the sequential loop's i-th request would have drawn), and the confuser
    draw uses a per-episode RandomState.  Scheduling order never leaks
    into the generated data.

    Returns:
        pairs: (h, e_pos, e_neg) numpy arrays for margin-ranking
        stats: dict with support/contradict/neutral counts
    """
    rng = np.random.RandomState(seed)
    splits = load_splits(dataset_name)
    class_names = get_class_names(dataset_name)
    encoder = get_sentence_encoder()
    kb = build_knowledge_base(dataset_name, encoder, splits=splits,
                              seed=seed)
    alarm = build_alarm_classifier(dataset_name, splits, seed)
    judge = RuleBasedJudge()

    X_train, y_train = splits["X_train"], splits["y_train"]
    n_episodes = max(1, n_triples // 3)
    # Stratified episode sampling (with replacement when the split is
    # smaller than the requested budget, e.g. CWRU).
    classes = np.unique(y_train)
    per_class = max(1, n_episodes // len(classes))
    sel = []
    for cls in classes:
        idx = np.where(y_train == cls)[0]
        sel.append(rng.choice(idx, size=per_class,
                              replace=per_class > len(idx)))
    sel = rng.permutation(np.concatenate(sel))

    def _episode_body(i, idx, ep_llm, ep_rng):
        hyp_gen = HypothesisGenerator(llm_client=ep_llm, encoder=encoder,
                                      M=1)
        alarm_result = alarm.classify(X_train[idx])
        hyp = hyp_gen.generate(alarm_result)
        h_emb = np.asarray(hyp["selected_embedding"], dtype=np.float32)
        y_true = int(y_train[idx])
        true_name = class_names[y_true]

        # Label by comparing stated diagnosis vs ground truth + judge
        ev_embs, ev_idx = _retrieve(kb, h_emb)
        verdict = judge.judge(hyp["selected"],
                              [kb.get_doc(j) for j in ev_idx],
                              features_mean=float(
                                  np.mean(alarm_result["features"])),
                              class_names=class_names)
        diag_id = diagnosis_to_class_id(hyp["selected"], class_names)
        if verdict["hallucinated"]:
            label = "contradict"
        elif diag_id == y_true:
            label = "support"
        else:
            label = "neutral"

        # Ranking pair: ground-truth-supporting vs confuser evidence
        confusers = [c for c in classes if c != y_true]
        confuser = int(diag_id) if (diag_id is not None
                                    and diag_id != y_true) \
            else int(ep_rng.choice(confusers))
        return (label, h_emb,
                _topk_class_evidence(kb, h_emb, true_name),
                _topk_class_evidence(kb, h_emb, class_names[confuser]))

    t0 = time.time()
    if workers > 1:
        from parallel_eval import iter_job_pool

        def _make_job(i, idx):
            def _run():
                if isinstance(llm, MockLLMClient):
                    ep_llm = MockLLMClient(dataset_name=dataset_name,
                                           seed=seed + i)
                else:
                    ep_llm = get_default_client(dataset_name=dataset_name,
                                                seed=seed + i)
                ep_rng = np.random.RandomState(seed * 7 + i)
                return _episode_body(i, idx, ep_llm, ep_rng)
            return _run

        jobs = [(i, _make_job(i, idx)) for i, idx in enumerate(sel)]
        results = [None] * len(sel)
        done = 0
        stats = {"support": 0, "contradict": 0, "neutral": 0}
        for key, res in iter_job_pool(jobs, workers):
            results[key] = res
            done += 1
            if verbose and done % 200 == 0:
                print(f"  [{dataset_name}] episode {done}/{len(sel)} "
                      f"({time.time()-t0:.0f}s)", flush=True)
    else:
        # Sequential path: single shared client/stream (legacy behaviour,
        # kept bit-reproducible for previous runs).
        stats = {"support": 0, "contradict": 0, "neutral": 0}
        results = []
        for i, idx in enumerate(sel):
            res = _episode_body(i, idx, llm, rng)
            results.append(res)
            if verbose and (i + 1) % 200 == 0:
                print(f"  [{dataset_name}] episode {i+1}/{len(sel)} "
                      f"({time.time()-t0:.0f}s)", flush=True)

    h_list, pos_list, neg_list = [], [], []
    for label, h_emb, pos, neg in results:
        stats[label] += 1
        h_list.append(h_emb)
        pos_list.append(pos)
        neg_list.append(neg)

    pairs = (np.stack(h_list), np.stack(pos_list), np.stack(neg_list))
    stats["n_episodes"] = len(sel)
    stats["n_triples"] = 3 * len(sel)
    return pairs, stats


def _retrieve(kb, h_emb, k=EVIDENCE_TOP_K):
    query = h_emb.reshape(1, -1).astype(np.float32)
    _, indices = kb.search(query, k)
    idx = [int(i) for i in indices[0] if int(i) >= 0]
    return np.array([kb.reconstruct(i) for i in idx]), idx


def _train_and_save(pairs, epochs, beta, device, out_path, model=None,
                    seed=RANDOM_SEED):
    """Fit a verifier on the pair pool and save the best checkpoint."""
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)
    h, ep, en = pairs
    n = len(h)
    n_val = max(1, int(0.1 * n))
    train = (h[:-n_val], ep[:-n_val], en[:-n_val])
    val = (h[-n_val:], ep[-n_val:], en[-n_val:])

    trainer = CAEVNTrainer(model=model, device=device, epochs=epochs,
                           entropy_beta=beta)
    best = MODEL_DIR / "caevn_best.pt"
    # train_model snapshots best-val weights to this SHARED path; clear
    # it first so a stale snapshot from another dataset, beta-grid run,
    # or architecture revision can never be loaded below.
    best.unlink(missing_ok=True)
    trainer.train_model(train, val_triples=val)
    if best.exists():  # best-val snapshot written during THIS training
        trainer.load(best)
    trainer.save(out_path)
    print(f"  saved {out_path}")


def main():
    parser = argparse.ArgumentParser(
        description="Train CAEVN verifiers from LLM-generated triples")
    parser.add_argument("--datasets", nargs="+",
                        default=["pq16", "cwru", "care"])
    parser.add_argument("--n-triples", type=int, default=9000,
                        help="target (hypothesis, evidence, label) "
                             "triples per dataset (paper: 9,000)")
    parser.add_argument("--epochs", type=int, default=CAEVN_EPOCHS)
    parser.add_argument("--seed", type=int, default=RANDOM_SEED)
    parser.add_argument("--beta", type=float, default=None,
                        help="entropy regularization; when set, the "
                             "checkpoint is saved as "
                             "caevn_{ds}_beta{beta}.pt (MOPSO grid)")
    parser.add_argument("--beta-grid", nargs="+", type=float, default=None,
                        help="train several entropy-beta checkpoints from "
                             "the same generated pair pool")
    parser.add_argument("--mock-llm", action="store_true",
                        help="use the deterministic MockLLMClient "
                             "(no GPU/vLLM; local testing)")
    parser.add_argument("--tag", default="",
                        help="checkpoint name tag; --tag boot1 writes "
                             "caevn_{ds}_boot1.pt and leaves the deployed "
                             "caevn_{ds}.pt untouched (verifier-training "
                             "resampling runs)")
    parser.add_argument("--skip-mlp", action="store_true",
                        help="do not train the MLP ablation verifier")
    parser.add_argument("--workers", type=int, default=0,
                        help="concurrent triple-generation episodes "
                             "(default env ASOC_EVAL_WORKERS or 16; "
                             "episode i always uses a client seeded "
                             "seed+i, so output is scheduling-independent)")
    args = parser.parse_args()

    device = "cuda" if torch.cuda.is_available() else "cpu"
    beta = args.beta if args.beta is not None else CAEVN_ENTROPY_BETA
    from parallel_eval import get_workers
    workers = args.workers if args.workers > 0 else get_workers()
    print(f"CAEVN training  datasets={args.datasets}  "
          f"n_triples={args.n_triples}  epochs={args.epochs}  "
          f"beta={beta}  device={device}  workers={workers}  "
          f"llm={'mock' if args.mock_llm else 'default'}")

    for ds in args.datasets:
        print(f"\n{'='*60}\nDataset: {ds}\n{'='*60}")
        llm = MockLLMClient(dataset_name=ds, seed=args.seed) \
            if args.mock_llm \
            else get_default_client(dataset_name=ds, seed=args.seed)

        pairs, stats = generate_triples(ds, args.n_triples, llm,
                                        args.seed, workers=workers)
        print(f"  triples: {stats}")

        tag = f"_{args.tag}" if args.tag else ""
        suffix = f"_beta{args.beta:g}" if args.beta is not None else ""
        _train_and_save(pairs, args.epochs, beta, device,
                        MODEL_DIR / f"caevn_{ds}{tag}{suffix}.pt",
                        seed=args.seed)

        for grid_beta in args.beta_grid or []:
            grid_out = MODEL_DIR / f"caevn_{ds}{tag}_beta{grid_beta:g}.pt"
            if grid_out == MODEL_DIR / f"caevn_{ds}{tag}{suffix}.pt":
                continue
            print(f"  training beta-grid checkpoint beta={grid_beta:g}")
            _train_and_save(pairs, args.epochs, grid_beta, device,
                            grid_out, seed=args.seed)

        if not args.skip_mlp and args.beta is None:
            print("  training MLP ablation verifier...")
            torch.manual_seed(args.seed)
            _train_and_save(pairs, args.epochs, beta, device,
                            MODEL_DIR / f"caevn_{ds}{tag}_mlp.pt",
                            model=MLPVerifier(), seed=args.seed)

        stats_out = MODEL_DIR / f"caevn_{ds}{tag}_train_stats.json"
        stats_out.write_text(json.dumps({
            "dataset": ds,
            "labels": stats,
            "args": {"n_triples": args.n_triples, "tag": args.tag,
                     "epochs": args.epochs, "seed": args.seed,
                     "beta": beta,
                     "beta_grid": args.beta_grid or [],
                     "mock_llm": bool(args.mock_llm)},
            "timestamp": time.strftime("%Y-%m-%dT%H:%M:%S"),
        }, indent=2))
        print(f"  stats -> {stats_out}")


if __name__ == "__main__":
    main()
