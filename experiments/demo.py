"""CPU demo of the CL-LLMOps pipeline.

Runs a minimal SVM baseline on a small slice of each dataset so that a
reviewer can verify the code is alive without needing a GPU or the
full vLLM stack. Four demo datasets are supported locally:

    python experiments/demo.py --dataset pq      # 5-class PQ (Kaggle)
    python experiments/demo.py --dataset pq16    # 16-class IEEE 1159 synthesis
    python experiments/demo.py --dataset cwru    # CWRU bearing fault
    python experiments/demo.py --dataset care    # CARE wind turbine SCADA
    python experiments/demo.py --all             # run all four in turn

Data sourcing notes:
    * pq   -- 5-class release jaideepreddykotla/powerqualitydistributiondataset1
              from Kaggle. Real data.
    * pq16 -- generated by data/generate_pq16.py (held back from public repo).
              Real deterministic synthesis per IEEE 1159-2019.
    * cwru -- downloaded via experiments/data/download_cwru.sh. Real data.
    * care -- if the raw Zenodo release is missing, falls back to a tiny
              synthetic SCADA stream.
"""

import argparse
import sys
import time
from pathlib import Path

THIS_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(THIS_DIR))

import numpy as np


def _header(title):
    print("=" * 60)
    print(title)
    print("=" * 60)


def _ensure_pq_data():
    from config import DATA_DIR
    pq_dir = DATA_DIR / "pq_classification"
    if pq_dir.exists() and any(pq_dir.glob("*.csv")):
        return pq_dir, "real"
    print(f"PQ data not found under {pq_dir}")
    print("Download the Kaggle release first:")
    print("    kaggle datasets download -d "
          "jaideepreddykotla/powerqualitydistributiondataset1")
    print(f"    unzip -q powerqualitydistributiondataset1.zip -d {pq_dir}")
    sys.exit(1)


def _ensure_pq16_data():
    from config import PROCESSED_DIR
    needed = [PROCESSED_DIR / f"pq16_{s}.npz" for s in ("train", "val", "test")]
    if all(p.exists() for p in needed):
        return PROCESSED_DIR, "synthetic (IEEE 1159)"
    missing = [p.name for p in needed if not p.exists()]
    print(f"PQ16 splits missing under {PROCESSED_DIR}: {missing}")
    print("Generate them first:")
    print("    python experiments/data/generate_pq16.py --n_per_class 400")
    sys.exit(1)


def _ensure_cwru_data():
    from config import DATA_DIR
    cwru_dir = DATA_DIR / "cwru"
    if cwru_dir.exists() and any(cwru_dir.glob("*.mat")):
        return cwru_dir, "real"
    print(f"CWRU data not found under {cwru_dir}")
    print("Download it first:")
    print("    bash experiments/data/download_cwru.sh")
    sys.exit(1)


def _ensure_care_data():
    from config import DATA_DIR, DATASETS
    care_dir = DATA_DIR / "care_wind"
    care_dir.mkdir(parents=True, exist_ok=True)
    real_csvs = [p for p in care_dir.glob("*.csv")
                 if not p.name.startswith("_synthetic_")]
    if real_csvs:
        return care_dir, "real"

    rng = np.random.default_rng(42)
    cfg = DATASETS["care"]
    n_tags = cfg["n_tags"]
    window = cfg["window_steps"]
    n_steps = 8 * window
    t = np.arange(n_steps)
    tags = []
    for _ in range(n_tags):
        base = rng.normal(0, 1, size=n_steps).cumsum() * 0.05
        trend = 0.001 * t + rng.normal(0, 0.2)
        tags.append(base + trend)
    df_values = np.stack(tags, axis=1).astype(np.float32)

    anomaly = np.zeros(n_steps, dtype=int)
    fault_start = int(n_steps * 0.55)
    fault_end = int(n_steps * 0.80)
    anomaly[fault_start:fault_end] = 1
    df_values[fault_start:fault_end] += rng.normal(
        0, 0.25, size=(fault_end - fault_start, n_tags)
    )

    import pandas as pd
    cols = [f"tag_{i:02d}" for i in range(n_tags)]
    df = pd.DataFrame(df_values, columns=cols)
    df["timestamp"] = pd.date_range("2026-01-01", periods=n_steps, freq="10min")
    df["anomaly"] = anomaly
    df = df[["timestamp"] + cols + ["anomaly"]]

    synth_path = care_dir / "_synthetic_smoke_test.csv"
    df.to_csv(synth_path, index=False)
    return care_dir, "synthetic"


def _flatten(X):
    if X.ndim == 2:
        return X.astype(np.float32)
    return X.reshape(X.shape[0], -1).astype(np.float32)


def _extract_or_pass(dataset_name, X_train, X_test):
    """Try FeatureExtractor; fall back to raw flatten on mismatch."""
    from features import FeatureExtractor
    if X_train.ndim == 2:
        print("    (pre-extracted features detected -- skipping FeatureExtractor)")
        return _flatten(X_train), _flatten(X_test), "flat"
    try:
        extractor = FeatureExtractor(dataset_name)
        train_feat = extractor.extract_batch(X_train)
        test_feat = extractor.extract_batch(X_test)
        return train_feat, test_feat, "structured"
    except Exception as exc:
        print(f"    (FeatureExtractor unavailable ({exc.__class__.__name__}) "
              f"-- using raw flatten)")
        return _flatten(X_train), _flatten(X_test), "flat"


DATASET_SLICES = {
    "pq":   {"train": 2000, "test": 500},
    "pq16": {"train": 4000, "test": 1000},
    "cwru": {"train": 1500, "test": 400},
    "care": {"train":  200, "test":  80},
}


def _run_one(dataset, trust):
    from data import load_splits
    from baselines.classical import SVMBaseline

    _header(f"CL-LLMOps Demo -- {dataset.upper()} ({trust}, CPU)")

    t0 = time.time()
    print(f"\n[1/3] Loading {dataset.upper()} splits ...")
    splits = load_splits(dataset)
    X_train, y_train = splits["X_train"], splits["y_train"]
    X_test, y_test = splits["X_test"], splits["y_test"]

    bounds = DATASET_SLICES[dataset]
    n_tr = min(bounds["train"], len(X_train))
    n_te = min(bounds["test"], len(X_test))
    X_train_s, y_train_s = X_train[:n_tr], y_train[:n_tr]
    X_test_s, y_test_s = X_test[:n_te], y_test[:n_te]
    print(f"    train={len(X_train_s):>5}  test={len(X_test_s):>5}  "
          f"classes={len(np.unique(y_train_s))}  "
          f"raw_shape={X_train_s.shape[1:]}")

    print(f"\n[2/3] Building features for {dataset.upper()} ...")
    X_train_feat, X_test_feat, mode = _extract_or_pass(dataset, X_train_s, X_test_s)
    print(f"    feature_dim={X_train_feat.shape[1]}  mode={mode}")

    if dataset == "cwru":
        noise_rate = 0.20
        rng = np.random.default_rng(123)
        n = len(y_train_s)
        flip_idx = rng.choice(n, size=int(n * noise_rate), replace=False)
        classes = np.unique(y_train_s)
        y_train_s = y_train_s.copy()
        for i in flip_idx:
            alt = rng.choice([c for c in classes if c != y_train_s[i]])
            y_train_s[i] = alt
        print(f"    (training-label noise injected: {len(flip_idx)}/{n} = "
              f"{noise_rate*100:.0f}% flipped; test labels untouched)")

    print("\n[3/3] Training SVM baseline and evaluating ...")
    svm = SVMBaseline()
    svm.train(X_train_feat, y_train_s)
    metrics = svm.evaluate(X_test_feat, y_test_s)

    elapsed = time.time() - t0
    print(f"\nDemo complete in {elapsed:.1f} s.")
    print(f"  accuracy : {metrics['accuracy']:.3f}")
    if "f1" in metrics:
        print(f"  macro F1 : {metrics['f1']:.3f}")
    if "top3_accuracy" in metrics:
        print(f"  top-3 acc: {metrics['top3_accuracy']:.3f}")

    print("\nSample predictions (first 10 test cases):")
    preds = svm.predict(X_test_feat[:10])
    for i, (p, y) in enumerate(zip(preds, y_test_s[:10])):
        marker = "v" if int(p) == int(y) else "x"
        print(f"  {i:>2}  predicted={int(p):>2}  true={int(y):>2}  {marker}")
    return elapsed, metrics


def main():
    parser = argparse.ArgumentParser(description="CL-LLMOps CPU smoke test.")
    parser.add_argument("--dataset",
                        choices=["pq", "pq16", "cwru", "care"],
                        default="pq",
                        help="dataset to run (default: pq)")
    parser.add_argument("--all", action="store_true",
                        help="run demos for all four datasets in turn")
    args = parser.parse_args()

    try:
        import config  # noqa: F401
        import data    # noqa: F401
        import baselines.classical  # noqa: F401
    except ImportError as exc:
        print(f"ERROR: missing dependency -- {exc}")
        print("Install requirements first:")
        print("    pip install -r experiments/requirements.txt")
        sys.exit(2)

    ensure = {
        "pq": _ensure_pq_data,
        "pq16": _ensure_pq16_data,
        "cwru": _ensure_cwru_data,
        "care": _ensure_care_data,
    }
    targets = ["pq", "pq16", "cwru", "care"] if args.all else [args.dataset]

    for ds in targets:
        _, trust = ensure[ds]()
        _run_one(ds, trust)
        print()

    print("Demo done.")


if __name__ == "__main__":
    main()
